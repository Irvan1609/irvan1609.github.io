import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseParameters,parseObservationNumber,observationKey,observationQueue,observationSummary,rawObservationTable,recapObservationTable,tableCsv,applyObservationChange,travelObservationHistory} from '../src/observation-engine.js';

const parameters=parseParameters('bb | Bobot buah | g\npb | Panjang buah | cm\ntb | Tebal buah | mm\nlb | Lebar buah | mm');
const plan={name:'Percobaan',parameters,units:[{id:'a',code:'U1G1',block:'1',treatment:'G1',count:5,kind:'buah'},{id:'b',code:'U1G2',block:'1',treatment:'G2',count:2,kind:'tanaman'}],groups:[{mode:'parameter',parameterIds:[parameters[0].id]},{mode:'sample',parameterIds:parameters.slice(1).map(p=>p.id)}],values:{},undo:[],redo:[]};
const code=s=>`${parameters.find(p=>p.id===s.parameterId).code}-${s.sample}`;
const queue=observationQueue(plan);
assert.deepEqual(queue.slice(0,20).map(code),['bb-1','bb-2','bb-3','bb-4','bb-5','pb-1','tb-1','lb-1','pb-2','tb-2','lb-2','pb-3','tb-3','lb-3','pb-4','tb-4','lb-4','pb-5','tb-5','lb-5']);
assert.deepEqual(queue.slice(20).map(code),['bb-1','bb-2','pb-1','tb-1','lb-1','pb-2','tb-2','lb-2']);
assert.equal(queue.length,28);
for(const [input,value] of [['0',0],['1,25',1.25],['-2.5',-2.5],['',null],['1e2',100]])assert.equal(parseObservationNumber(input),value);
for(const input of ['1,2.3','abc','1 000','Infinity','1e999'])assert.throws(()=>parseObservationNumber(input));
assert.throws(()=>parseParameters('bb\nBB'),/berulang/);
const key1=observationKey('a',1,parameters[0].id),key2=observationKey('a',2,parameters[0].id),key3=observationKey('a',3,parameters[0].id);
applyObservationChange(plan,key1,{status:'measured',value:0});
applyObservationChange(plan,key2,{status:'measured',value:10});
applyObservationChange(plan,key3,{status:'missing',value:null});
const summary=observationSummary(plan)[0];
assert.deepEqual([summary.n,summary.mean,summary.sum,summary.missing,summary.pending],[2,5,10,1,2]);
assert.equal(observationSummary(plan).at(-1).mean,null);
assert.equal(observationSummary(plan).at(-1).sum,null);
const before=structuredClone(plan.values);
plan.groups.reverse();assert.equal(observationQueue(plan)[0].parameterId,parameters[1].id);assert.deepEqual(plan.values,before);
assert.equal(travelObservationHistory(plan,'undo'),true);assert.equal(plan.values[key3],undefined);
assert.equal(travelObservationHistory(plan,'redo'),true);assert.equal(plan.values[key3].status,'missing');
assert.equal(rawObservationTable(plan).rows.length,28);
assert.equal(rawObservationTable(plan).rows[0][4],'U1G1(1)');
assert.equal(recapObservationTable(plan).rows[0][3],5);
parameters[0].reducer='sum';assert.equal(recapObservationTable(plan).rows[0][3],10);
const manual={...plan,orderMode:'manual',manualOrder:queue.slice(0,20).map(code).join(', ')};
assert.deepEqual(observationQueue(manual).map(q=>q.key),queue.map(q=>q.key));
assert.throws(()=>observationQueue({...manual,manualOrder:manual.manualOrder+', bb-1'}),/dua kali/);
assert.throws(()=>observationQueue({...manual,manualOrder:'bb-1'}),/setiap parameter/);
assert.throws(()=>observationQueue({...plan,units:[...plan.units,{...plan.units[0],id:'c'}]}),/berulang/);
assert.throws(()=>observationQueue({...plan,units:[{...plan.units[0],count:0}]}),/1–500/);
const harvest=parseParameters('bb-p1 | Panen satu | g\nbb-p2 | Panen dua | g');
const harvestPlan={...plan,parameters:harvest,units:[{...plan.units[0],count:1}],orderMode:'manual',manualOrder:'bb-p2-1, bb-p1-1'};
assert.deepEqual(observationQueue(harvestPlan).map(q=>q.parameterId),[harvest[1].id,harvest[0].id]);
assert.match(tableCsv({headers:['Kode'],rows:[['=1+1']]}),/'=1\+1/);
const observationUi=readFileSync(new URL('../src/observation-workflow.js',import.meta.url),'utf8');
const datasetBridge=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
for(const id of ['obsDataset','obsSourceDataset','obsOpenDataset','obsImportUnits','obsMapApply','datasetNavTab']){
  assert.match(observationUi,new RegExp(id),'Observation UI must provide dataset access: '+id);
}
assert.match(observationUi,/readDataset\?\.\(requested\)/,'Unit mapping must read the selected dataset, not just the active one');
assert.match(observationUi,/sourceDataset:plan\.sourceDataset/,'Existing observation sessions must retain their dataset choice');
assert.match(observationUi,/if\(starterOnly\)draft\.units=\[\]/,'Dataset import must replace the untouched demo unit');
for(const api of ['listDatasets','readDataset','activateDataset'])assert.match(datasetBridge,new RegExp('\\b'+api+':async|\\b'+api+':\\('),'Dataset bridge must expose '+api);
console.log('Observation dataset picker contract OK: source selection, persistence, mapping, and editor navigation.');
console.log('Observation checks passed: mixed order, unequal samples, stable identities, harvest codes, missing/zero values, recap, undo/redo, and CSV safety.');
