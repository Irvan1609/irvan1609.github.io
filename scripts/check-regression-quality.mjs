import assert from 'node:assert/strict';
import {polynomialRegression} from '../src/advanced-engine.js';
import {assessPolynomialRegression} from '../src/regression-quality.js';
const near=(a,b,t=1e-7)=>assert.ok(Math.abs(a-b)<=t*Math.max(1,Math.abs(b)),`${a} != ${b}`);
const rows=[];
for(const x of [0,1,2,3,4])for(const e of [-.1,0,.1])rows.push([x,2+3*x-.5*x*x+e]);
const result=assessPolynomialRegression(polynomialRegression(rows,3));
assert.equal(result.selectionCriterion,'AICc');
assert.equal(result.bestDegree,2);
assert.equal(result.uniqueX,5);
const quadratic=result.models.find(m=>m.degree===2);
assert.ok(Number.isFinite(quadratic.aicc));
assert.ok(quadratic.lackOfFit);
near(quadratic.lackOfFit.ss,0,1e-6);
assert.ok(quadratic.lackOfFit.p>.95);
const noRep=assessPolynomialRegression(polynomialRegression([[0,1],[1,2],[2,4],[3,7],[4,11]],2));
assert.equal(noRep.dfPure,0);
assert.ok(noRep.warnings.some(x=>/lack-of-fit tidak tersedia/i.test(x)));
console.log('Regression quality verified: AICc selection penalizes unnecessary polynomial degree and replicated doses provide a pure-error lack-of-fit test.');
